#!/usr/bin/env python3
"""Generate components/hy_core/src/tzdb_data.c from the vendored posix_tz_db zones.csv.

Usage: tools/gen_tzdb.py third_party/posix_tz_db/zones.csv components/hy_core/src/tzdb_data.c

Source: https://github.com/nayarsystems/posix_tz_db (MIT, licence file next to zones.csv)
Source tag: none (the repository publishes no tags or releases)
Source commit: 93447c0ddac304ca6672a5fd905261c7e8905159 (default branch head, 2025-09-29;
               last data update "Timezone update 2025b-1", fb5fa340cfa7599467358a347e5d6e6724d92bb2)

Rows whose POSIX string is HY_TZ_LEN (components/hy_core/include/hy/types.h) characters or
longer cannot be stored in a time-zone buffer and are dropped; their names are printed.
Output layout: names sorted by strcmp order, a table of unique POSIX strings and one
index per name into that table. Output is deterministic.
"""
import csv
import os
import re
import sys

SOURCE_COMMIT = "93447c0ddac304ca6672a5fd905261c7e8905159"


def tz_len():
    here = os.path.dirname(os.path.abspath(__file__))
    types_h = os.path.join(here, "..", "components", "hy_core", "include", "hy", "types.h")
    with open(types_h, encoding="utf-8") as f:
        m = re.search(r"#define\s+HY_TZ_LEN\s+(\d+)", f.read())
    if not m:
        sys.exit("HY_TZ_LEN not found in types.h")
    return int(m.group(1))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    limit = tz_len()
    rows = {}
    with open(sys.argv[1], newline="", encoding="utf-8") as f:
        for r in csv.reader(f):
            if len(r) != 2:
                sys.exit("bad row: %r" % (r,))
            name, posix = r
            if len(posix) >= limit:
                print("dropped (POSIX string >= %d chars): %s" % (limit, name))
                continue
            rows[name] = posix
    names = sorted(rows)
    uniq = sorted(set(rows.values()))
    index = {p: i for i, p in enumerate(uniq)}
    if len(uniq) > 255:
        sys.exit("too many unique POSIX strings for uint8_t index")

    def q(s):
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = []
    out.append("/* Generated by tools/gen_tzdb.py from third_party/posix_tz_db/zones.csv; do not edit.")
    out.append(" * Source: github.com/nayarsystems/posix_tz_db, commit %s (no tags published). */" % SOURCE_COMMIT)
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("const size_t hy_tzdb_n = %d;" % len(names))
    out.append("")
    out.append("const char *const hy_tzdb_posix_tab[%d] = {" % len(uniq))
    out.extend("    %s," % q(p) for p in uniq)
    out.append("};")
    out.append("")
    out.append("const char *const hy_tzdb_names[%d] = {" % len(names))
    out.extend("    %s," % q(n) for n in names)
    out.append("};")
    out.append("")
    regions = []
    for n in names:
        r = n.split("/")[0]
        if r not in regions:
            regions.append(r)
    out.append("const size_t hy_tzdb_region_n = %d;" % len(regions))
    out.append("")
    out.append("const char *const hy_tzdb_region_tab[%d] = {" % len(regions))
    out.extend("    %s," % q(r) for r in regions)
    out.append("};")
    out.append("")
    out.append("const uint8_t hy_tzdb_posix_idx[%d] = {" % len(names))
    for i in range(0, len(names), 16):
        out.append("    " + ", ".join(str(index[rows[n]]) for n in names[i:i + 16]) + ",")
    out.append("};")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


main()

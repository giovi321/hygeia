#!/usr/bin/env python3
"""Bundles the web UI into a C table of gzipped files.

    web_bundle.py --src web --out build/web_assets.c [--limit 204800]

The scripts named in <src>/bundle.txt (one path per line, '#' starts a comment) are joined in that order into
app.js. index.html, app.css, app.js and favicon.svg are gzipped (level 9, mtime 0, no file name). The CSS and JS
are served as /app.<first 8 hex of sha256>.css|js and index.html is rewritten to name them. Nothing else under
<src> is served. The build fails when the gzipped total is above the limit (200 KB).
"""

import argparse
import gzip
import hashlib
import io
import os
import sys
from collections import namedtuple

LIMIT = 200 * 1024

Asset = namedtuple("Asset", "path mime gz immutable")


class BundleError(Exception):
    pass


def _read(path):
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError as e:
        raise BundleError("cannot read %s: %s" % (path, e))


def gzip_bytes(data):
    buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, compresslevel=9, mtime=0) as g:
        g.write(data)
    return buf.getvalue()


def gunzip(data):
    return gzip.decompress(data)


def bundle_list(src):
    names = []
    for line in _read(os.path.join(src, "bundle.txt")).decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    if not names:
        raise BundleError("bundle.txt names no script")
    return names


def join_scripts(src, names):
    parts = []
    for n in names:
        data = _read(os.path.join(src, n))
        if not data.endswith(b"\n"):
            data += b"\n"
        parts.append(data)
    return b"".join(parts)


def short_hash(data):
    return hashlib.sha256(data).hexdigest()[:8]


def rewrite_index(html, css_path, js_path):
    out = html
    for old, new in (("app.css", css_path), ("app.js", js_path)):
        hits = 0
        for q in ('"', "'"):
            for prefix in ("/", ""):
                ref = q + prefix + old + q
                hits += out.count(ref)
                out = out.replace(ref, q + new + q)
        if hits == 0:
            raise BundleError("index.html does not reference %s" % old)
    return out


def build(src):
    """The served files, in a fixed order: index.html, the CSS, the JS, favicon.svg."""
    css = _read(os.path.join(src, "app.css"))
    js = join_scripts(src, bundle_list(src))
    css_path = "/app.%s.css" % short_hash(css)
    js_path = "/app.%s.js" % short_hash(js)
    html = rewrite_index(_read(os.path.join(src, "index.html")).decode("utf-8"), css_path, js_path)
    icon = _read(os.path.join(src, "favicon.svg"))
    return [
        Asset("/index.html", "text/html; charset=utf-8", gzip_bytes(html.encode("utf-8")), False),
        Asset(css_path, "text/css; charset=utf-8", gzip_bytes(css), True),
        Asset(js_path, "text/javascript; charset=utf-8", gzip_bytes(js), True),
        Asset("/favicon.svg", "image/svg+xml", gzip_bytes(icon), False),
    ]


def check_size(assets, limit=LIMIT):
    total = sum(len(a.gz) for a in assets)
    if total > limit:
        raise BundleError("web bundle is %d bytes gzipped, above the %d byte limit" % (total, limit))
    return total


def _c_bytes(data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return "\n".join(lines)


def render_c(assets):
    out = ["/* Generated by tools/web_bundle.py from web/. Do not edit. */",
           '#include "web_internal.h"', ""]
    for i, a in enumerate(assets):
        out.append("static const uint8_t s_a%d[%d] = {" % (i, len(a.gz)))
        out.append(_c_bytes(a.gz))
        out.append("};")
        out.append("")
    out.append("const hy_web_asset_t hy_web_assets[] = {")
    for i, a in enumerate(assets):
        out.append('    {"%s", "%s", s_a%d, %d, %s},' % (a.path, a.mime, i, len(a.gz),
                                                       "true" if a.immutable else "false"))
    out.append("};")
    out.append("const size_t hy_web_assets_n = %d;" % len(assets))
    out.append("const size_t hy_web_assets_bytes = %d;" % sum(len(a.gz) for a in assets))
    out.append("")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--limit", type=int, default=LIMIT)
    args = ap.parse_args(argv)
    try:
        assets = build(args.src)
        total = check_size(assets, args.limit)
    except BundleError as e:
        print("web_bundle: error: %s" % e, file=sys.stderr)
        return 1
    text = render_c(assets)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("web_bundle: %d files, %d bytes gzipped (limit %d)" % (len(assets), total, args.limit))
    return 0


if __name__ == "__main__":
    sys.exit(main())
